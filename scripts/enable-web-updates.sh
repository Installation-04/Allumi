#!/usr/bin/env bash
# Install or refresh the root-owned host updater (run from the server checkout).
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
if [ "${1:-}" = --help ]; then
  printf '%s\n' 'Usage: sudo ./scripts/enable-web-updates.sh' 'Requires active systemd and Python 3. Preserves only the exact generated Compose override.'
  exit 0
fi
[ "$#" -eq 0 ] || die "argument inconnu (voir --help)."
require_root
require_env
[[ "$ALLUMI_DIR" =~ ^/[A-Za-z0-9/_-]+$ ]] || die "chemin du dépôt non pris en charge"
command -v python3 >/dev/null || die "Installe python3 d'abord."
command -v systemctl >/dev/null || die "Installe systemd d'abord."
systemctl show --property=Version --value >/dev/null 2>&1 || die "Un gestionnaire systemd actif est nécessaire."

# Accept the legacy generated bytes too: a refresh must never replace a custom
# override or follow a symlink, including a dangling one.
override="$ALLUMI_DIR/compose.override.yaml"
expected="$(cat <<'YAML'
services:
  app:
    environment:
      ALLUMI_UPDATE_DIR: /app/storage/update-control
    volumes:
      - /var/lib/allumi-update:/app/storage/update-control
YAML
)"
if [ -L "$override" ]; then
  die "compose.override.yaml est un lien symbolique : intègre manuellement le montage documenté."
elif [ -e "$override" ]; then
  [ -f "$override" ] && cmp -s "$override" <(printf '%s\n' "$expected") || die "compose.override.yaml est personnalisé : intègre manuellement le montage documenté."
fi

# Link atomically without replacing a file created between validation and setup.
if [ ! -e "$override" ]; then
  temporary="$(mktemp "$ALLUMI_DIR/.compose.override.XXXXXX")"
  trap 'rm -f "$temporary"' EXIT
  printf '%s\n' "$expected" > "$temporary"
  chmod 0644 "$temporary"
  ln "$temporary" "$override" || die "compose.override.yaml existe maintenant : aucun écrasement effectué."
  rm -f "$temporary"
  trap - EXIT
fi
install -d -m 0755 /var/lib/allumi-update
chown 1000:1000 /var/lib/allumi-update
install -m 0755 "$ALLUMI_DIR/scripts/update-agent.py" /usr/local/sbin/allumi-update-agent
cat > /etc/systemd/system/allumi-update.service <<UNIT
[Unit]
Description=Allumi requested server update
After=docker.service network-online.target
Requires=docker.service
[Service]
Type=oneshot
Environment=ALLUMI_DIR=$ALLUMI_DIR
WorkingDirectory=$ALLUMI_DIR
ExecStart=/usr/bin/python3 /usr/local/sbin/allumi-update-agent
TimeoutStartSec=40min
UMask=0022
UNIT
cat > /etc/systemd/system/allumi-update.timer <<'UNIT'
[Unit]
Description=Check for an administrator-requested Allumi update
[Timer]
OnBootSec=60
OnUnitInactiveSec=30
[Install]
WantedBy=timers.target
UNIT
systemctl daemon-reload
systemctl enable --now allumi-update.timer
cd "$ALLUMI_DIR"
compose up -d app
info "Agent activé. Journal : journalctl -u allumi-update.service"
